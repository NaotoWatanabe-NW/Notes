/**
 * 進捗の％とページの行き来。
 *
 * 画面では％で入れてもらい、保存はこれまでどおりページで持つ
 * （引用のページや振り返りの「◯◯ページ読んだ」がページを前提にしているため）。
 */

/**
 * 総ページが分からない本に入れる分母。
 *
 * 電子書籍は版や表示設定でページ数が変わるので、総ページを聞かずに
 * 「100 のうち何」として％をそのまま持つ。振り返りの「◯◯ページ読んだ」には
 * この本が 100 ページとして混ざる（分からない本を 0 と数えるかの選び）。
 */
export const PERCENT_TOTAL = 100

/**
 * 「◯％まで読んだ」を、保存するページ数に直す。
 *
 * 100％ちょうどのときだけ最後のページを返す。それ以外は切り捨てる。
 * 四捨五入にすると、短い本で 99％ が総ページに届いてしまい、
 * サーバー側の「最後まで読んだら読了」に引っかかって、読み終えていない本が
 * 勝手に読了になる。
 */
export function pageFromPercent(percent: number, total: number): number {
  if (percent >= 100) return total
  if (percent <= 0) return 0
  return Math.floor((total * percent) / 100)
}
